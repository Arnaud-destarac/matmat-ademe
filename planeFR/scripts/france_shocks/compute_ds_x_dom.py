"""
Computes dS, the relative change of S (= F_x_dom / x) between each 2050 scenario
(S1-S4, TEND) and Base_year_2015, for the manually shocked extensions (all the
dom_<lp> sheets of my_manual_param.xlsx), from the shocks defined in that file.

For a given row_name and scenario:
    F_x_dom_2050 = F_x_dom_base_year * (1 + shock)   (shock applied to all sectors)
    S_base       = F_x_dom_base_year / x_base_year
    S_2050       = F_x_dom_2050 / x_2050
    dS           = S_2050 / S_base - 1

dS is initialized to 0 for all indicators (same format as the Fx_* sheets of
S_extraction.xlsx: indicators as rows, sectors as columns); only the rows whose
row_name is in my_manual_param.xlsx AND whose shock is filled in and non-zero
are recomputed (a 0 or empty shock means "not calibrated yet" and leaves dS=0;
otherwise dS would become the compensating ratio that cancels the volume effect
of x). The row_names of my_manual_param.xlsx missing from S_extraction.xlsx are
ignored.

dS_x_dom (.pkl and .xlsx) is written, by scenario and by shocked extension, into
MatMat/matmat-ademe/.../2-shocks/1-transitions_2050/<scenario>/extensions/dom_<lp>/,
together with the two files the engine needs to load it:
    - detail_levels.xlsx, copied from the France accounts the engine shocks
      (Outputs/France/Base_year_2015/extensions/dom_<lp>/, written by
      update_calib_fr): extension categories + regions / sectors / final
      demand categories, the same as the system of the shock scenarios;
    - info.json: that of the system of the scenario, plus extension_name.
Only the extensions with a non-zero dS_x_dom get a folder: the engine skips
the extensions without a shock folder. A folder whose dS_x_dom has become
entirely zero (shocks reset to 0 or emptied), or of an extension which no
longer has a dom_<lp> sheet in my_manual_param.xlsx, is therefore deleted
here, so that the engine does not apply an outdated shock.

The "F_Y_tot" shocks of the same file have no sectoral dimension: they are
applied directly, in place, in
Module_PlaneFR/data/Outputs_MatMat/<version>/[<group>/]<scenario>/extensions/dom_<lp>/F_Y_tot.pkl,
recomputing each time new_value = base_year value (FY_<lp> sheet of
S_extraction.xlsx) x (1 + shock). Starting from the base_year value (and not
from the value already in the F_Y_tot.pkl of the scenario) makes the script
idempotent without a backup: rerunning it never compounds the shock, even if
the scenario file has been regenerated by the upstream model in between.

These shocks are applied to all the scenario folders of data/<version>,
whatever their group (no_SSP, SSP2_2050, "_agri" groups, groups assembled by
hand...): the scenario of a folder is read in its system/info.json
(scenario_name = S1...TEND, base_year = BASE_YEAR) and not deduced from its
name, so that a renamed or copied folder (e.g. SSP_all/S1+) does get the shock
of its scenario.

reformat_d_cba_monde_europe.py rewrites F_Y_tot.pkl to its base_year value in
all the scenario folders: this script must therefore be run after it. The
--only-f-y-tot option only applies the F_Y_tot shocks, without recomputing the
dS_x_dom (useful at the end of a chain when the engine will not be rerun).
"""

import argparse
import json
import shutil
import sys
from pathlib import Path

import pandas as pd

# Shared modules of planeFR/scripts/_common
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "_common"))
from planefr_paths import DATA_VERSION_DIR, MATMAT_DIR, find_all_scenario_dirs, MODULE_INPUT_SHOCKS_DIR, PARAMETERS_DIR  # noqa: E402
from planefr_utils import make_pickle_portable  # noqa: E402

S_EXTRACTION_FILE = MODULE_INPUT_SHOCKS_DIR / "S_extraction.xlsx"
MANUAL_PARAM_FILE = PARAMETERS_DIR / "a-manual_shocks" / "my_manual_param.xlsx"
SHOCKS_OUTPUT_DIR = MATMAT_DIR / "data" / "4-PlaneFR" / "2-shocks" / "1-transitions_2050"

BASE_YEAR_NAME = "Base_year_2015"
# France accounts shocked by the engine (update_calib_fr output): source of the
# detail_levels.xlsx of the shocked extensions
CALIB_ACCOUNTS_DIR = MATMAT_DIR / "data" / "4-PlaneFR" / "Outputs" / "France" / BASE_YEAR_NAME
# Base year of the shocked scenarios (base_year of their system/info.json): that
# of the FY_<lp> values of S_extraction.xlsx (BASE_YEAR_NAME)
BASE_YEAR = "2015"
SCENARIO_FOLDER_NAMES = {
    "S1": "S1_2050",
    "S2": "S2_2050",
    "S3": "S3_2050",
    "S4": "S4_2050",
    "TEND": "TEND_2050",
}


def find_scenario_dirs(data_dir):
    """Scenario folders (containing extensions/) of data_dir, whether directly
    below it (data/<version>/<scenario>) or in a group folder
    (data/<version>/<group>/<scenario>, e.g. no_SSP/S1_2050, SSP_all/S1+)."""
    found = []
    for top in sorted(p for p in data_dir.iterdir() if p.is_dir()):
        if (top / "extensions").is_dir():
            found.append(top)
            continue
        found.extend(sub for sub in sorted(top.iterdir()) if (sub / "extensions").is_dir())
    return found


def read_scenario_info(scenario_dir):
    """system/info.json of a scenario folder (empty dict if missing, e.g. the
    non-France 2019_<region> folders)."""
    info_path = scenario_dir / "system" / "info.json"
    if not info_path.is_file():
        return {}
    return json.loads(info_path.read_text(encoding="utf-8-sig"))


def find_shocked_scenario_dirs():
    """{scenario (S1...TEND): [scenario folders]} for all the folders of
    DATA_VERSION_DIR whose system/info.json carries this scenario_name and the
    base year BASE_YEAR. The base years without shock (empty scenario_name,
    Base_year_agri...) are not retained."""
    by_scenario = {short: [] for short in SCENARIO_FOLDER_NAMES}
    for scenario_dir in find_all_scenario_dirs():
        info = read_scenario_info(scenario_dir)
        if info.get("scenario_name") in by_scenario and str(info.get("base_year")) == BASE_YEAR:
            by_scenario[info["scenario_name"]].append(scenario_dir)
    return by_scenario


def get_manual_lp_names():
    """Sub-processes (lp) having a dom_<lp> sheet in my_manual_param.xlsx."""
    sheet_names = pd.ExcelFile(MANUAL_PARAM_FILE).sheet_names
    return [name[len("dom_"):] for name in sheet_names if name.startswith("dom_")]


def load_x_domestic():
    """'x' sheet of S_extraction.xlsx, restricted to the domestic sectors (same
    region/category/sub_category/sector columns as F_x_dom)."""
    x = pd.read_excel(S_EXTRACTION_FILE, sheet_name="x", header=list(range(5)), index_col=0)
    return x.xs("domestic", axis=1, level="origin")


def load_f_x_dom_base(lp_name):
    return pd.read_excel(S_EXTRACTION_FILE, sheet_name=f"Fx_{lp_name}", header=list(range(4)), index_col=0)


def load_f_y_tot_base(lp_name):
    return pd.read_excel(S_EXTRACTION_FILE, sheet_name=f"FY_{lp_name}", header=list(range(2)), index_col=0)


def load_manual_shocks(lp_name):
    """Rebuilds a clean table from my_manual_param.xlsx: row 1 holds the
    scenario names (S1..TEND), row 3 the field names (variable, row_region,
    row_name, ...), the data start on row 4."""
    raw = pd.read_excel(MANUAL_PARAM_FILE, sheet_name=f"dom_{lp_name}", header=None)
    scenario_cols = raw.iloc[0, 7:].tolist()
    field_cols = raw.iloc[2, 0:7].tolist()
    data = raw.iloc[3:].reset_index(drop=True)
    data.columns = field_cols + scenario_cols
    return data


def compute_ds(lp_name, x_dom):
    f_base = load_f_x_dom_base(lp_name)
    ds_by_scenario = {
        short: pd.DataFrame(0.0, index=f_base.index, columns=f_base.columns) for short in SCENARIO_FOLDER_NAMES
    }

    shocks = load_manual_shocks(lp_name)
    x_shocks = shocks[shocks["variable"] == "F_x_dom"]

    for _, row in x_shocks.iterrows():
        row_name = row["row_name"]
        if row_name not in f_base.index:
            print(f"[skip] {lp_name}: row_name '{row_name}' missing from Fx_{lp_name} (S_extraction.xlsx), ignored.")
            continue

        f_row_base = f_base.loc[row_name]
        s_base = f_row_base / x_dom.loc[BASE_YEAR_NAME]

        for short, folder_name in SCENARIO_FOLDER_NAMES.items():
            shock = row[short]
            if pd.isna(shock) or shock == 0:
                continue
            f_row_2050 = f_row_base * (1 + shock)
            s_2050 = f_row_2050 / x_dom.loc[folder_name]
            ds_row = (s_2050 / s_base - 1).replace([float("inf"), float("-inf")], 0.0).fillna(0.0)
            ds_by_scenario[short].loc[row_name] = ds_row

    return ds_by_scenario


def remove_extension_dir(ext_dir):
    """Deletes the shock folder of an extension (dS_x_dom of a previous run),
    so that an outdated shock is not applied."""
    if ext_dir.exists():
        shutil.rmtree(ext_dir)
        print(f"[remove] {ext_dir}")


def remove_orphan_extension_dirs(lp_names):
    """Deletes the extension shock folders that are not dom_<lp> of an
    extension of my_manual_param.xlsx."""
    kept = {f"dom_{lp}" for lp in lp_names}
    for scenario_dir in (d for d in SHOCKS_OUTPUT_DIR.iterdir() if d.is_dir()):
        extensions_dir = scenario_dir / "extensions"
        if not extensions_dir.is_dir():
            continue
        for ext_dir in extensions_dir.iterdir():
            if ext_dir.name not in kept:
                remove_extension_dir(ext_dir) if ext_dir.is_dir() else ext_dir.unlink()


def write_extension_metadata(lp_name, out_dir):
    """detail_levels.xlsx (copied from the France accounts the engine shocks)
    and info.json (system/info.json of the scenario + extension_name)."""
    ext_name = f"dom_{lp_name}"
    calib_dl = CALIB_ACCOUNTS_DIR / "extensions" / ext_name / "detail_levels.xlsx"
    if not calib_dl.is_file():
        raise FileNotFoundError(f"Detail levels not found (run update_calib_fr first?): {calib_dl}")
    shutil.copyfile(calib_dl, out_dir / "detail_levels.xlsx")
    info = {**read_scenario_info(out_dir.parents[1]), "extension_name": ext_name}
    (out_dir / "info.json").write_text(json.dumps(info, indent=2), encoding="utf-8")


def write_ds_outputs(lp_name, ds_by_scenario):
    for short, folder_name in SCENARIO_FOLDER_NAMES.items():
        ds = ds_by_scenario[short]
        out_dir = SHOCKS_OUTPUT_DIR / folder_name / "extensions" / f"dom_{lp_name}"
        if (ds == 0).all().all():
            # no F_x_dom shock for this scenario/extension pair: the shock
            # folder of a previous run must not remain
            remove_extension_dir(out_dir)
            continue

        out_dir.mkdir(parents=True, exist_ok=True)
        if not isinstance(ds.index, pd.MultiIndex):
            ds.index = pd.MultiIndex.from_arrays([ds.index], names=ds.index.names)
        make_pickle_portable(ds).to_pickle(out_dir / "dS_x_dom.pkl")
        ds.to_excel(out_dir / "dS_x_dom.xlsx", sheet_name="dS_x_dom")
        write_extension_metadata(lp_name, out_dir)
        print(f"[write] {out_dir / 'dS_x_dom.xlsx'} (+ .pkl, detail_levels.xlsx, info.json)")


def apply_f_y_tot_shocks(lp_name, scenario_dirs):
    """Applies the F_Y_tot shocks of the extension to all the scenario folders.

    scenario_dirs: {scenario (S1...TEND): [folders]}, see find_shocked_scenario_dirs.
    """
    shocks = load_manual_shocks(lp_name)
    y_shocks = shocks[shocks["variable"] == "F_Y_tot"]
    if y_shocks.empty:
        return
    fy_base = load_f_y_tot_base(lp_name)

    for _, row in y_shocks.iterrows():
        row_name = row["row_name"]
        if row_name not in fy_base.index:
            print(f"[skip] {lp_name}: row_name '{row_name}' missing from FY_{lp_name} (S_extraction.xlsx), ignored.")
            continue
        base_value = fy_base.loc[row_name]

        for short in SCENARIO_FOLDER_NAMES:
            shock = row[short]
            if pd.isna(shock) or shock == 0:
                continue

            for scenario_dir in scenario_dirs[short]:
                label = scenario_dir.relative_to(DATA_VERSION_DIR).as_posix()
                f_y_path = scenario_dir / "extensions" / f"dom_{lp_name}" / "F_Y_tot.pkl"
                if not f_y_path.exists():
                    # The F_Y_tot.pkl of the scenario is created by
                    # reformat_d_cba_monde_europe in the folders produced by the
                    # engine, which itself needs the dS_x_dom written above: the
                    # computation of the dS is not blocked, it will be enough to
                    # rerun this script after engine + reformat.
                    print(f"[skip] {label}/dom_{lp_name}: F_Y_tot.pkl missing (engine/reformat_d_cba_monde_europe not run yet?), shock '{row_name}' not applied.")
                    continue
                f_y = pd.read_pickle(f_y_path)
                if row_name not in f_y.index:
                    print(f"[skip] {label}/dom_{lp_name}: '{row_name}' missing from F_Y_tot.pkl, ignored.")
                    continue

                f_y.loc[row_name] = base_value * (1 + shock)
                f_y.to_pickle(f_y_path)
                print(f"[update] {label}/dom_{lp_name}/F_Y_tot.pkl : '{row_name}' = base_year x (1{shock:+.4f})")


def main():
    parser = argparse.ArgumentParser(
        description="Computes the dS_x_dom of the manual shocks and applies the F_Y_tot shocks."
    )
    parser.add_argument(
        "--only-f-y-tot",
        action="store_true",
        help="only applies the F_Y_tot shocks, without recomputing or rewriting the dS_x_dom",
    )
    args = parser.parse_args()

    scenario_dirs = find_shocked_scenario_dirs()
    for short, dirs in scenario_dirs.items():
        names = ", ".join(d.relative_to(DATA_VERSION_DIR).as_posix() for d in dirs) or "none"
        print(f"[scenarios] {short} : {len(dirs)} folder(s) ({names})")

    x_dom = None if args.only_f_y_tot else load_x_domestic()
    lp_names = get_manual_lp_names()
    if not args.only_f_y_tot:
        remove_orphan_extension_dirs(lp_names)

    for lp_name in lp_names:
        print(f"=== {lp_name} ===")
        if not args.only_f_y_tot:
            ds_by_scenario = compute_ds(lp_name, x_dom)
            write_ds_outputs(lp_name, ds_by_scenario)
        apply_f_y_tot_shocks(lp_name, scenario_dirs)


if __name__ == "__main__":
    main()
